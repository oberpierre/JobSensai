import subprocess
import unittest
from pathlib import Path
from unittest.mock import patch

from publisher.publisher import AGENT_TRAILER, Publisher

_BASENAME = "acme_com_extraction_v1"

_PATHS = [
    f"adapters/adapters/{_BASENAME}.py",
    f"adapters/adapters/{_BASENAME}_test.py",
    f"adapters/adapters/fixtures/{_BASENAME}",
]


def _ok(stdout: str = "https://github.com/acme/repo/pull/7\n"):
    return subprocess.CompletedProcess([], 0, stdout=stdout, stderr="")


def _publish(
    passed: bool,
    model_name: str = "qwen3-coder:30b",
    paths=_PATHS,
    base_branch: str = "main",
    existing: bool | None = False,
):
    pub = Publisher(repo_root=Path("/repo"), base_branch=base_branch)
    with patch.object(Publisher, "has_existing_pr", return_value=existing):
        return pub.publish(
            basename=_BASENAME,
            domain="acme.com",
            adapter_type="extraction",
            passed=passed,
            test_output="TEST LOG OUTPUT",
            model_name=model_name,
            paths=paths,
            kind="adapter",
        )


def _commands(mock_run) -> list[tuple]:
    return [tuple(call.args[0]) for call in mock_run.call_args_list]


def _git_commands(mock_run) -> list[tuple]:
    return [c for c in _commands(mock_run) if c[0] == "git"]


class TestPublisher(unittest.TestCase):
    @patch("publisher.publisher.subprocess.run")
    def test_green_opens_a_ready_pr_and_returns_url(self, mock_run):
        mock_run.return_value = _ok()
        url = _publish(passed=True)
        self.assertEqual(url, "https://github.com/acme/repo/pull/7")

        cmds = _commands(mock_run)
        # Branch is taken off the fetched remote base, one branch per adapter.
        git = _git_commands(mock_run)
        branch_step = git.index(
            ("git", "checkout", "-B", f"feature/adapter-{_BASENAME}", "origin/main")
        )
        self.assertEqual(
            git[branch_step - 1],
            ("git", "fetch", "origin", "+refs/heads/main:refs/remotes/origin/main"),
        )
        self.assertIn(
            ("git", "push", "--force", "-u", "origin", f"feature/adapter-{_BASENAME}"),
            cmds,
        )
        # Only this adapter's three paths are staged — never BUILD or other adapters.
        add = next(c for c in cmds if c[:2] == ("git", "add"))
        self.assertEqual(
            add,
            (
                "git",
                "add",
                "--",
                f"adapters/adapters/{_BASENAME}.py",
                f"adapters/adapters/{_BASENAME}_test.py",
                f"adapters/adapters/fixtures/{_BASENAME}",
            ),
        )
        # Green commit carries a validated (^) risk and the agent trailer.
        commit = next(c for c in cmds if c[:2] == ("git", "commit"))
        self.assertTrue(any(part.startswith("^ F") for part in commit), commit)
        self.assertIn(
            "Co-Authored-By: JobSensai Agent <agent@jobsensai.oberpierre.com>", commit
        )
        # A ready PR: gh pr create WITHOUT --draft.
        gh = next(c for c in cmds if c[0] == "gh")
        self.assertNotIn("--draft", gh)

    @patch("publisher.publisher.subprocess.run")
    def test_red_opens_a_draft_pr_with_broken_risk(self, mock_run):
        mock_run.return_value = _ok()
        _publish(passed=False)

        cmds = _commands(mock_run)
        commit = next(c for c in cmds if c[:2] == ("git", "commit"))
        self.assertTrue(any(part.startswith("@ F") for part in commit), commit)
        gh = next(c for c in cmds if c[0] == "gh")
        self.assertIn("--draft", gh)

    @patch("publisher.publisher.subprocess.run")
    def test_pr_body_names_the_model_that_generated_the_adapter(self, mock_run):
        mock_run.return_value = _ok()
        _publish(passed=True, model_name="qwen3.8:27b-mlx")

        gh = next(c for c in _commands(mock_run) if c[0] == "gh")
        body = gh[gh.index("--body") + 1]
        self.assertIn("Generated by `qwen3.8:27b-mlx`.", body)

    @patch("publisher.publisher.subprocess.run")
    def test_red_run_is_still_a_draft_and_still_names_the_model(self, mock_run):
        mock_run.return_value = _ok()
        _publish(passed=False, model_name="qwen3.8:27b-mlx")

        gh = next(c for c in _commands(mock_run) if c[0] == "gh")
        self.assertIn("--draft", gh)
        body = gh[gh.index("--body") + 1]
        self.assertIn("Generated by `qwen3.8:27b-mlx`.", body)

    @patch("publisher.publisher.subprocess.run")
    def test_stages_exactly_the_paths_it_is_given(self, mock_run):
        mock_run.return_value = _ok()
        _publish(
            passed=True,
            paths=[
                "adapters/adapters/mappings/foo.json",
                "adapters/adapters/mappings/foo_test.py",
            ],
        )

        add = next(c for c in _commands(mock_run) if c[:2] == ("git", "add"))
        self.assertEqual(
            add,
            (
                "git",
                "add",
                "--",
                "adapters/adapters/mappings/foo.json",
                "adapters/adapters/mappings/foo_test.py",
            ),
        )

    @patch("publisher.publisher.subprocess.run")
    def test_returns_none_when_a_git_step_fails(self, mock_run):
        mock_run.side_effect = subprocess.CalledProcessError(1, ["git", "push"])
        self.assertIsNone(_publish(passed=True))

    @patch("publisher.publisher.subprocess.run")
    def test_red_commit_skips_the_hook_and_commits_only_the_paths(self, mock_run):
        mock_run.return_value = _ok()
        _publish(passed=False)

        commit = next(c for c in _commands(mock_run) if c[:2] == ("git", "commit"))
        subject = "@ F Add a generated extraction adapter for acme.com"
        self.assertEqual(
            list(commit),
            ["git", "commit", "--no-verify", "-m", subject, "-m", AGENT_TRAILER]
            + ["--", *_PATHS],
        )

    @patch("publisher.publisher.subprocess.run")
    def test_green_commit_runs_the_hook_and_commits_only_the_paths(self, mock_run):
        mock_run.return_value = _ok()
        _publish(passed=True)

        cmds = _commands(mock_run)
        commit = next(c for c in cmds if c[:2] == ("git", "commit"))
        subject = "^ F Add a generated extraction adapter for acme.com"
        self.assertEqual(
            list(commit),
            ["git", "commit", "-m", subject, "-m", AGENT_TRAILER] + ["--", *_PATHS],
        )
        self.assertFalse(any("--no-verify" in c for c in cmds))

    @patch("publisher.publisher.subprocess.run")
    def test_a_failed_commit_logs_its_stdout_and_stderr(self, mock_run):
        def run(args, **_kwargs):
            if tuple(args[:2]) == ("git", "commit"):
                raise subprocess.CalledProcessError(
                    1,
                    ["git", "commit"],
                    output="OUT-TEXT",
                    stderr="pre-commit: ruff found lint errors.",
                )
            return _ok()

        mock_run.side_effect = run
        with self.assertLogs("publisher.publisher", level="ERROR") as logs:
            self.assertIsNone(_publish(passed=True))

        self.assertEqual(len(logs.records), 1)
        message = logs.records[0].getMessage()
        self.assertIn("OUT-TEXT", message)
        self.assertIn("pre-commit: ruff found lint errors.", message)

    @patch("publisher.publisher.subprocess.run")
    def test_clone_is_left_on_the_base_branch(self, mock_run):
        """The runner is long-lived: the next adapter branches off main, not this."""
        mock_run.return_value = _ok()
        _publish(passed=True)

        self.assertEqual(
            _git_commands(mock_run)[-2:],
            [("git", "checkout", "main"), ("git", "reset", "-q", "--", *_PATHS)],
        )

    @patch("publisher.publisher.subprocess.run")
    def test_base_branch_is_restored_even_when_publishing_fails(self, mock_run):
        # Every git call raises, so the restore must not turn that into an
        # escaping error.
        mock_run.side_effect = subprocess.CalledProcessError(1, ["git", "push"])
        self.assertIsNone(_publish(passed=True))
        self.assertEqual(
            _git_commands(mock_run)[-2:],
            [("git", "checkout", "main"), ("git", "reset", "-q", "--", *_PATHS)],
        )


class TestHasExistingPr(unittest.TestCase):
    def setUp(self):
        self.pub = Publisher(repo_root=Path("/repo"))

    @patch("publisher.publisher.subprocess.run")
    def test_true_when_gh_reports_a_pr(self, mock_run):
        mock_run.return_value = _ok('[{"number":7}]\n')
        self.assertIs(self.pub.has_existing_pr(_BASENAME, kind="adapter"), True)

        cmd = _commands(mock_run)[0]
        self.assertEqual(cmd[:2], ("gh", "pr"))
        self.assertIn(f"feature/adapter-{_BASENAME}", cmd)
        # Includes closed PRs count
        self.assertIn("all", cmd)

    @patch("publisher.publisher.subprocess.run")
    def test_false_on_an_empty_list(self, mock_run):
        mock_run.return_value = _ok("[]\n")
        self.assertIs(self.pub.has_existing_pr(_BASENAME, kind="adapter"), False)

    @patch("publisher.publisher.subprocess.run")
    def test_none_when_gh_fails(self, mock_run):
        """Undeterminable must be distinct from absent so the caller can fail closed."""
        mock_run.side_effect = subprocess.CalledProcessError(1, ["gh"])
        self.assertIsNone(self.pub.has_existing_pr(_BASENAME, kind="adapter"))

    @patch("publisher.publisher.subprocess.run")
    def test_none_when_gh_is_not_installed(self, mock_run):
        mock_run.side_effect = FileNotFoundError("gh")
        self.assertIsNone(self.pub.has_existing_pr(_BASENAME, kind="adapter"))

    def test_branch_name_is_derived_from_the_basename(self):
        """The branch is the idempotency key, so it must match what publish() pushes."""
        self.assertEqual(
            self.pub.branch_for(_BASENAME, kind="adapter"),
            f"feature/adapter-{_BASENAME}",
        )

    def test_branch_name_takes_the_kind_it_is_given(self):
        self.assertEqual(self.pub.branch_for("x", kind="mapping"), "feature/mapping-x")
        self.assertEqual(self.pub.branch_for("x", kind="adapter"), "feature/adapter-x")

    def test_branch_for_requires_kind(self):
        """A defaulted kind fails silently: it would publish to one namespace and
        check another."""
        with self.assertRaises(TypeError):
            self.pub.branch_for("x")

    @patch("publisher.publisher.subprocess.run")
    def test_has_existing_pr_requires_kind(self, mock_run):
        with self.assertRaises(TypeError):
            self.pub.has_existing_pr(_BASENAME)

    @patch("publisher.publisher.subprocess.run")
    def test_publish_requires_kind(self, mock_run):
        mock_run.return_value = _ok()
        pub = Publisher(repo_root=Path("/repo"))
        with self.assertRaises(TypeError):
            pub.publish(
                basename=_BASENAME,
                domain="acme.com",
                adapter_type="extraction",
                passed=True,
                test_output="TEST LOG OUTPUT",
                model_name="qwen3-coder:30b",
                paths=_PATHS,
            )

    @patch("publisher.publisher.subprocess.run")
    def test_has_existing_pr_checks_the_branch_for_its_own_kind(self, mock_run):
        """A mapping check must look at the mapping branch, not the adapter one."""
        mock_run.return_value = _ok("[]\n")
        self.pub.has_existing_pr(_BASENAME, kind="mapping")

        cmd = _commands(mock_run)[0]
        self.assertIn(f"feature/mapping-{_BASENAME}", cmd)

    @patch("publisher.publisher.subprocess.run")
    def test_check_and_publish_name_the_same_branch_for_one_kind(self, mock_run):
        """The already-published check and the publish that follows it must name
        one branch for a given kind, since the branch is the idempotency key."""

        # The real has_existing_pr runs twice here, so it must answer "none yet".
        def run(args, **_kwargs):
            if tuple(args[:3]) == ("gh", "pr", "list"):
                return _ok("[]\n")
            return _ok()

        mock_run.side_effect = run
        pub = Publisher(repo_root=Path("/repo"))
        pub.has_existing_pr(_BASENAME, kind="mapping")
        pub.publish(
            basename=_BASENAME,
            domain="acme.com",
            adapter_type="extraction",
            passed=True,
            test_output="TEST LOG OUTPUT",
            model_name="qwen3-coder:30b",
            paths=_PATHS,
            kind="mapping",
        )

        cmds = _commands(mock_run)
        check_cmd = next(c for c in cmds if c[:2] == ("gh", "pr"))
        push_cmd = next(c for c in cmds if c[:2] == ("git", "push"))
        check_branch = check_cmd[check_cmd.index("--head") + 1]
        push_branch = push_cmd[-1]
        self.assertEqual(check_branch, push_branch)


